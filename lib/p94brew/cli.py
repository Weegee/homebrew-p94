"""Output, argument parsing and exit handling shared by all commands (p94-hig, text part).

Deviation from FAR-4: the program setting for colour is ``HOMEBREW_P94_COLOR``, because
``brew`` passes only ``HOMEBREW_*`` variables to external commands (Homebrew ``bin/brew:304-316``).
``NO_COLOR`` arrives as ``HOMEBREW_NO_COLOR`` and is honoured as well.
Deviation from TXT-2: texts generated by argparse itself stay English.
"""

from __future__ import annotations

import argparse
import os
import re
import shutil
import signal
import sys
import textwrap
from collections.abc import Callable, Mapping, Sequence
from typing import IO, NoReturn

EXIT_OK = 0
EXIT_ERROR = 1
EXIT_USAGE = 2

_RED = "\033[31m"
_YELLOW = "\033[33m"
_GREEN = "\033[32m"
_BOLD = "\033[1m"
_RESET = "\033[0m"


class Fehler(Exception):
    """Expected error: reported without a stack trace (FEH-3)."""


def _environ(env: Mapping[str, str] | None) -> Mapping[str, str]:
    return os.environ if env is None else env


def use_color(stream: IO[str], choice: str = "auto", env: Mapping[str, str] | None = None) -> bool:
    """Decide on colour in the order of FAR-4."""
    env = _environ(env)
    if choice in ("always", "never"):
        return choice == "always"
    if env.get("NO_COLOR") or env.get("HOMEBREW_NO_COLOR"):
        return False
    if env.get("FORCE_COLOR", "0") not in ("", "0"):
        return True
    if env.get("TERM", "") in ("", "dumb"):
        return False
    return bool(stream.isatty())


def utf8_ok(env: Mapping[str, str] | None = None) -> bool:
    """True if the first set locale variable names a UTF-8 charset."""
    env = _environ(env)
    for name in ("LC_ALL", "LC_CTYPE", "LANG"):
        value = env.get(name) or env.get(f"HOMEBREW_{name}")
        if value:
            return "utf-8" in value.lower() or "utf8" in value.lower()
    return False


def plural(n: int, one: str, many: str) -> str:
    """``plural(1, "Formel", "Formeln")`` gives ``"1 Formel"``."""
    return f"{n} {one if n == 1 else many}"


class Output:
    """Results to stdout, every message to stderr (KAN-1)."""

    def __init__(
        self,
        prog: str,
        color: str = "auto",
        quiet: bool = False,
        verbose: int = 0,
        env: Mapping[str, str] | None = None,
        out: IO[str] | None = None,
        err: IO[str] | None = None,
    ) -> None:
        self.prog = prog
        self.quiet = quiet
        self.verbose = verbose
        self.out = out if out is not None else sys.stdout
        self.err = err if err is not None else sys.stderr
        self.color_out = use_color(self.out, color, env)
        self.color_err = use_color(self.err, color, env)
        utf8 = utf8_ok(env)
        self.ok_sym = "✓" if utf8 else "OK"
        self.fail_sym = "✗" if utf8 else "FEHLER"
        self.warn_sym = "⚠" if utf8 else "WARNUNG"

    @staticmethod
    def _paint(text: str, code: str, enabled: bool) -> str:
        return f"{code}{text}{_RESET}" if enabled else text

    def error(self, msg: str) -> None:
        label = self._paint("Fehler:", _RED, self.color_err)
        print(f"{self.prog}: {label} {msg}", file=self.err)

    def warn(self, msg: str) -> None:
        label = self._paint("Warnung:", _YELLOW, self.color_err)
        print(f"{self.prog}: {label} {msg}", file=self.err)

    def note(self, msg: str) -> None:
        if not self.quiet:
            sym = self._paint(self.ok_sym, _GREEN, self.color_err)
            print(f"{sym} {msg}", file=self.err)

    def info(self, msg: str) -> None:
        if not self.quiet:
            print(msg, file=self.err)

    def detail(self, msg: str) -> None:
        if self.verbose >= 1:
            print(msg, file=self.err)

    def heading(self, msg: str) -> None:
        if not self.quiet:
            print(self._paint(msg, _BOLD, self.color_err), file=self.err)

    def result(self, line: str) -> None:
        print(line, file=self.out)

    def check(self, ok: bool | None, label: str, detail: str = "") -> None:
        """One check line: ``ok`` True, False or None (warning)."""
        if ok is None:
            sym = self._paint(self.warn_sym, _YELLOW, self.color_out)
        elif ok:
            sym = self._paint(self.ok_sym, _GREEN, self.color_out)
        else:
            sym = self._paint(self.fail_sym, _RED, self.color_out)
        print(f"{sym} {label}", file=self.out)
        if detail:
            for line in detail.splitlines():
                print(f"  {line}", file=self.out)

    def table(self, header: Sequence[str], rows: Sequence[Sequence[str]]) -> None:
        """Columns separated by two spaces; the last column is not padded."""
        all_rows = [list(header), *[list(r) for r in rows]]
        widths = [max(len(r[i]) for r in all_rows) for i in range(len(header))]
        for row in all_rows:
            cells = [c.ljust(widths[i]) for i, c in enumerate(row[:-1])] + [row[-1]]
            print("  ".join(cells).rstrip(), file=self.out)


def _translate(message: str) -> str:
    """Translate the argparse messages that users meet most often (rest stays English)."""
    if message.startswith("unrecognized arguments: "):
        rest = message[len("unrecognized arguments: ") :]
        kind = "unbekannte Option" if rest.startswith("-") else "unerwartetes Argument"
        return f"{kind}: {rest}"
    if message.startswith("the following arguments are required: "):
        return "Pflichtargument fehlt: " + message.split(": ", 1)[1]
    match = re.fullmatch(r"argument (.+): invalid choice: (.+) \(choose from (.+)\)", message)
    if match:
        allowed = ", ".join(part.strip().strip("'") for part in match.group(3).split(","))
        return f"ungültiger Wert {match.group(2)} für {match.group(1)}; erlaubt: {allowed}"
    return message


class _Parser(argparse.ArgumentParser):
    def error(self, message: str) -> NoReturn:
        message = _translate(message)
        self.print_usage(sys.stderr)
        self.exit(EXIT_USAGE, f"{self.prog}: Fehler: {message}\nHilfe: {self.prog} --help\n")


class _Help(argparse.RawDescriptionHelpFormatter):
    """Keep the layout of description and epilog, wrap lines wider than the terminal (MOD-4)."""

    def _fill_text(self, text, width, indent):
        wrap = {"width": max(width, 20), "break_long_words": False, "break_on_hyphens": False}
        filled = []
        for line in text.split("\n"):
            body = line.lstrip()
            if not body:
                filled.append("")
                continue
            lead = indent + line[: len(line) - len(body)]
            hang = lead + ("  " if body.startswith("-") else "    " if lead != indent else "")
            filled.append(textwrap.fill(body, initial_indent=lead, subsequent_indent=hang, **wrap))
        return "\n".join(filled)

    def add_usage(self, usage, actions, groups, prefix=None):
        return super().add_usage(usage, actions, groups, prefix or "Aufruf: ")


def make_parser(prog: str, description: str, epilog: str | None = None) -> argparse.ArgumentParser:
    """Parser with German usage prefix and error message; exit 2 on usage errors (KAN-3)."""
    kwargs: dict = {
        "prog": prog,
        "description": description,
        "epilog": epilog,
        "formatter_class": _Help,
        "add_help": False,
        "allow_abbrev": False,
    }
    if sys.version_info >= (3, 14):
        kwargs.update(suggest_on_error=True, color=True)
    return _Parser(**kwargs)


def add_common_options(parser: argparse.ArgumentParser, version: str) -> None:
    """Add -q, -v, --color, -h and -V in the group "Optionen" (ARG-4, ARG-7)."""
    group = parser.add_argument_group("Optionen")
    group.add_argument("-q", "--quiet", action="store_true", help="nur Fehler ausgeben")
    group.add_argument("-v", "--verbose", action="count", default=0, help="mehr ausgeben")
    group.add_argument(
        "--color",
        choices=("auto", "always", "never"),
        default=os.environ.get("HOMEBREW_P94_COLOR", "auto"),
        help="Farbe: auto, always oder never (Vorgabe: auto)",
    )
    group.add_argument("-h", "--help", action="help", help="diese Hilfe zeigen")
    group.add_argument(
        "-V", "--version", action="version", version=f"{parser.prog} {version}",
        help="Version zeigen",
    )  # fmt: skip


def run_main(prog: str, main: Callable[[Sequence[str] | None], int], argv=None) -> NoReturn:
    """Run ``main`` and translate errors and signals into exit codes (SIG-1 to SIG-4)."""

    def _on_term(*_: object) -> NoReturn:
        sys.exit(143)

    signal.signal(signal.SIGTERM, _on_term)
    try:
        rc = main(argv)
        sys.stdout.flush()  # raise a broken pipe here, not at interpreter exit
        sys.exit(rc)
    except Fehler as exc:
        Output(prog).error(str(exc))
        sys.exit(EXIT_ERROR)
    except KeyboardInterrupt:
        print(f"\n{prog}: abgebrochen", file=sys.stderr)
        sys.exit(130)
    except BrokenPipeError:
        devnull = os.open(os.devnull, os.O_WRONLY)
        os.dup2(devnull, sys.stdout.fileno())
        sys.exit(EXIT_ERROR)


def terminal_width() -> int:
    """``COLUMNS`` first, then the terminal, else 80 (MOD-4)."""
    return shutil.get_terminal_size((80, 24)).columns
